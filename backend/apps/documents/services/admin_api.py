def analytics_payload() -> dict:
    qs = DocumentRequest.objects.select_related('document_type')
    total = qs.count()
    with_outputs = qs.filter(outputs__isnull=False).distinct().count()
    auto_rate = round((with_outputs / total) * 100, 1) if total else 0.0

    reservations = Reservation.objects.all()
    res_total = reservations.count()
    res_success = reservations.filter(
        status__in=[Reservation.Status.COMPLETED, Reservation.Status.CHECKED_IN, Reservation.Status.APPROVED]
    ).count()
    reservation_success = round((res_success / res_total) * 100, 1) if res_total else 0.0

    processing_times = []
    for row in (
        qs.filter(reviewed_at__isnull=False, submitted_at__isnull=False)
        .values('document_type__category')
        .distinct()
    ):
        category = row['document_type__category']
        subset = qs.filter(
            document_type__category=category,
            reviewed_at__isnull=False,
            submitted_at__isnull=False,
        ).only('submitted_at', 'reviewed_at')
        hours = [
            (r.reviewed_at - r.submitted_at).total_seconds() / 3600
            for r in subset
            if r.reviewed_at and r.submitted_at
        ]
        if hours:
            processing_times.append({
                'service': category,
                'avgHours': round(sum(hours) / len(hours), 1),
            })

    delivery_counts: Counter[str] = Counter()
    for req in qs.only('metadata_json'):
        method = (req.metadata_json or {}).get('deliveryMethod', 'digital')
        delivery_counts[method] += 1

    in_review = qs.filter(status=DocumentRequest.Status.IN_REVIEW, submitted_at__isnull=False)
    review_hours = [
        (timezone.now() - r.submitted_at).total_seconds() / 3600
        for r in in_review
        if r.submitted_at
    ]
    bottlenecks = []
    if review_hours:
        bottlenecks.append({
            'step': 'verify',
            'avgHours': round(sum(review_hours) / len(review_hours), 1),
        })

    return {
        'processingTimes': processing_times,
        'reservationSuccessRate': reservation_success,
        'autoGenerationRate': auto_rate,
        'bottlenecks': bottlenecks,
        'workloadHeatmap': [],
        'deliveryAnalytics': [
            {'method': method, 'count': count}
            for method, count in delivery_counts.most_common()
        ],
    }
