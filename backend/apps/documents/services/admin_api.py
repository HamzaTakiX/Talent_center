def resources_payload() -> list:
    today = timezone.now().date()
    bookable = AdministrativeResource.objects.filter(is_active=True, is_bookable=True)
    result = []
    for resource in bookable:
        reservations_today = Reservation.objects.filter(
            resource=resource,
            start_at__date=today,
            status__in=[
                Reservation.Status.PENDING,
                Reservation.Status.APPROVED,
                Reservation.Status.CHECKED_IN,
            ],
        ).count()
        capacity = max(1, resource.capacity or 1)
        occupancy = min(100, round((reservations_today / capacity) * 100))
        result.append({
            'id': str(resource.pk),
            'code': resource.code,
            'name': resource.name,
            'resourceType': resource.resource_type.lower(),
            'location': resource.location,
            'capacity': resource.capacity,
            'isActive': resource.is_active,
            'occupancyPercent': occupancy,
        })
    return result


